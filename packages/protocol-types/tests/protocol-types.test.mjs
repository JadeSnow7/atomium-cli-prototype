import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const testDir = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(testDir, '..');
const repoRoot = resolve(pkgRoot, '../..');
const generatedDir = join(pkgRoot, 'src', 'generated');
const indexPath = join(pkgRoot, 'src', 'index.ts');
const rustBindingsDir = join(repoRoot, 'crates', 'atomium-protocol', 'bindings');

function parseIndexExports(indexSource) {
  const exports = [];
  const re = /^export\s+type\s+\{\s*([A-Za-z0-9_]+)\s*\}\s+from\s+"\.\/generated\/([A-Za-z0-9_]+)";$/gm;
  let match;
  while ((match = re.exec(indexSource)) !== null) {
    exports.push({ symbol: match[1], fileBase: match[2] });
  }
  return exports;
}

test('every generated .ts file in src/generated is re-exported by src/index.ts', () => {
  const generatedFiles = readdirSync(generatedDir)
    .filter((name) => name.endsWith('.ts'))
    .sort();
  assert.ok(generatedFiles.length > 0, 'Expected generated .ts files in src/generated');

  const indexSource = readFileSync(indexPath, 'utf8');
  const exports = parseIndexExports(indexSource);
  const exportedBases = new Set(exports.map((e) => e.fileBase));

  for (const file of generatedFiles) {
    const base = file.slice(0, -3);
    assert.ok(
      exportedBases.has(base),
      `Generated type file src/generated/${file} is not re-exported in src/index.ts`,
    );
  }
});

test('every export referenced in src/index.ts exists on disk under src/generated/', () => {
  const indexSource = readFileSync(indexPath, 'utf8');
  const exports = parseIndexExports(indexSource);
  assert.ok(exports.length > 0, 'Expected export type statements in src/index.ts');

  for (const { symbol, fileBase } of exports) {
    assert.equal(symbol, fileBase, `Exported symbol ${symbol} should match file ${fileBase}.ts`);
    const targetPath = join(generatedDir, `${fileBase}.ts`);
    assert.ok(existsSync(targetPath), `Missing generated file for export: ${targetPath}`);
  }
});

test('every generated .ts file has ts-rs header and valid export type definition', () => {
  const generatedFiles = readdirSync(generatedDir)
    .filter((name) => name.endsWith('.ts'))
    .sort();

  for (const file of generatedFiles) {
    const base = file.slice(0, -3);
    const content = readFileSync(join(generatedDir, file), 'utf8');
    assert.match(
      content,
      /^\/\/ This file was generated by \[ts-rs\]\(https:\/\/github\.com\/Aleph-Alpha\/ts-rs\)\./m,
      `Missing ts-rs header in ${file}`,
    );
    const exportTypeRe = new RegExp(`^export\\s+type\\s+${base}\\s*=`, 'm');
    assert.match(
      content,
      exportTypeRe,
      `Missing "export type ${base} =" definition in ${file}`,
    );
  }
});

test('crates/atomium-protocol/bindings matches src/generated when present', (t) => {
  if (!existsSync(rustBindingsDir)) {
    t.skip('crates/atomium-protocol/bindings not present');
    return;
  }

  const generatedFiles = readdirSync(generatedDir)
    .filter((name) => name.endsWith('.ts'))
    .sort();
  const bindingFiles = readdirSync(rustBindingsDir)
    .filter((name) => name.endsWith('.ts'))
    .sort();

  assert.deepEqual(
    generatedFiles,
    bindingFiles,
    'src/generated file list differs from crates/atomium-protocol/bindings',
  );

  for (const file of generatedFiles) {
    const genContent = readFileSync(join(generatedDir, file), 'utf8');
    const bindContent = readFileSync(join(rustBindingsDir, file), 'utf8');
    assert.equal(
      genContent,
      bindContent,
      `Generated file ${file} is out of sync with crates/atomium-protocol/bindings/${file}`,
    );
  }
});
